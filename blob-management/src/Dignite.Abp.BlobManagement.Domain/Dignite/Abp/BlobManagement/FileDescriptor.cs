using System;
using System.Security.Cryptography;
using System.Text;
using Volo.Abp;
using Volo.Abp.Auditing;
using Volo.Abp.Domain.Entities;
using Volo.Abp.MultiTenancy;

namespace Dignite.Abp.BlobManagement;

/// <summary>
/// One file of a managed container: the record of bytes that <see cref="FileDescriptorManager"/> stored there. Every
/// BLOB the module holds has one, whichever way it came in; tenant usage is computed from this table.
/// <para>
/// <b>Two ways in</b>, both an application's. It saves a BLOB under a name of its own (the BLOB storing provider, the
/// BLOB API): that name is its address - the application reads it back by it - unique among the descriptors of
/// its tenant and container, held by the <see cref="NameKey"/>, which the database keeps unique
/// (<see cref="IsAddressedByName"/>). Or it keeps a file for its user (the file API): it is addressed by its id, its
/// name is a display name and may repeat, and it can be filed in a directory (<see cref="DirectoryId"/>), renamed and
/// moved.
/// </para>
/// <para>
/// <b>Two names.</b> <see cref="Name"/> is the caller's. <see cref="BlobName"/> is the physical BLOB in the container's
/// storage, generated by the module, and the descriptor's alone: two files never share stored bytes, even when they
/// hold the same content, so a BLOB goes with its descriptor.
/// </para>
/// <para>
/// <b>Deleted for good.</b> A descriptor that is deleted is removed, not marked: its bytes are deleted with it, and
/// the module has no trash to restore either from.
/// </para>
/// </summary>
public class FileDescriptor : AggregateRoot<Guid>, ICreationAuditedObject, IModificationAuditedObject, IMultiTenant
{
    protected FileDescriptor()
    {
    }

    /// <param name="nameIsAddress">Whether <paramref name="name"/> is the file's address - a BLOB an application saved -
    /// so the descriptor holds the <see cref="NameKey"/>, for as long as it exists.</param>
    public FileDescriptor(
        Guid id,
        string containerName,
        string name,
        string blobName,
        string mimeType,
        long size,
        string? hash,
        string? clientId = null,
        Guid? tenantId = null,
        bool nameIsAddress = false)
        : base(id)
    {
        ContainerName = Check.NotNullOrWhiteSpace(containerName, nameof(containerName), FileDescriptorConsts.MaxContainerNameLength);
        Name = Check.NotNullOrWhiteSpace(name, nameof(name), FileDescriptorConsts.MaxNameLength);
        BlobName = Check.NotNullOrWhiteSpace(blobName, nameof(blobName), FileDescriptorConsts.MaxBlobNameLength);
        MimeType = Check.NotNullOrWhiteSpace(mimeType, nameof(mimeType), FileDescriptorConsts.MaxMimeTypeLength);
        Size = size;
        Hash = Check.Length(hash, nameof(hash), FileDescriptorConsts.MaxHashLength);
        ClientId = Check.Length(clientId, nameof(clientId), FileDescriptorConsts.MaxClientIdLength);
        TenantId = tenantId;
        NameKey = nameIsAddress ? CreateNameKey(tenantId, containerName, name) : null;
    }

    /// <summary>The Blob Management container the bytes are stored in (a container declared with <c>UseBlobManagementContainer</c>).</summary>
    public virtual string ContainerName { get; protected set; } = default!;

    /// <summary>
    /// The caller's name for the file. For a file an application saved under a name it is the address: the BLOB name
    /// it was saved under, kept as it was given (it may be a path). For a file kept by id it is a display name.
    /// </summary>
    public virtual string Name { get; protected set; } = default!;

    /// <summary>
    /// The physical BLOB in the container's storage: 32 random hexadecimal digits and the canonical extension of
    /// the stored type, generated by <see cref="FileDescriptorManager"/>. No other descriptor names it.
    /// </summary>
    public virtual string BlobName { get; protected set; } = default!;

    /// <summary>Detected from the stored content, never the caller's claim.</summary>
    public virtual string MimeType { get; protected set; } = default!;

    /// <summary>
    /// The SHA-256 (base64) of the uploaded bytes, before the container's contributors transformed them, that the caller
    /// sent with the upload and the module verified; <c>null</c> for a file stored without one, which costs no hash
    /// (<c>dev-docs/upload-checksum-decision.md</c>).
    /// </summary>
    public virtual string? Hash { get; protected set; }

    /// <summary>The size of the stored bytes, after the container's pipeline contributors ran.</summary>
    public virtual long Size { get; protected set; }

    /// <summary>
    /// On a descriptor an application saved under a name, the SHA-256 (upper-case hex) of
    /// <c>{tenant}:{container}:{name}</c> (<see cref="CreateNameKey"/>), set when it is created and kept for as long as
    /// it exists; <c>null</c> on a file kept by id, whose name may repeat. Unique in the database, so two simultaneous
    /// saves under one name cannot both leave a descriptor, and the key a name is looked up by - never the name column,
    /// whose comparison follows the database's collation. A hash rather than the address itself, since unique-index
    /// keys are size-limited and a name may be long.
    /// </summary>
    public virtual string? NameKey { get; protected set; }

    /// <summary>
    /// The directory a file kept by id is filed in, or <c>null</c> at the top of its container. Always <c>null</c> for a
    /// file addressed by its name, and in a container without directories. Whether a directory may hold the file is
    /// <see cref="FileDescriptorManager"/>'s check.
    /// </summary>
    public virtual Guid? DirectoryId { get; protected set; }

    /// <summary>
    /// The OAuth client that stored the file over HTTP - through the BLOB API or the file API - or <c>null</c> when an
    /// application in Blob Management's own host stored it.
    /// </summary>
    public virtual string? ClientId { get; protected set; }

    /// <summary>
    /// Whether anyone may read the file at its public address, without signing in - the business system's call, not
    /// the container's: it marks a file public when it stores it (the provider's <c>IsPublic</c> for a BLOB saved
    /// under a name, the input's for a file kept by id) or later (<see cref="FileDescriptorManager.SetPublicAsync"/>).
    /// The address is the name for a file saved under one, else its <see cref="BlobName"/>.
    /// </summary>
    public virtual bool IsPublic { get; protected set; }

    /// <summary>
    /// Whether the file came in through an upload ticket and its business system has not confirmed it yet - has not
    /// filed it with a record of its own (<see cref="FileDescriptorManager.ConfirmAsync"/>). A pending file is left out
    /// of listings, gets no read link and is never read publicly; it is counted in the usage and the allocation, and
    /// one left pending past <c>BlobManagementUploadOptions.PendingLifetime</c> is deleted.
    /// </summary>
    public virtual bool IsPending { get; protected set; }

    /// <summary>
    /// When the bytes the file holds were stored: when it was created, or - for a BLOB saved under a name - when it was
    /// last saved over (<see cref="ReplaceContent"/>). It is the <c>Last-Modified</c> of a read.
    /// </summary>
    public virtual DateTime CreationTime { get; set; }

    /// <summary>
    /// The user the file is counted for in the usage figures, and nothing else - no right comes with it: the
    /// application's current user as ABP's auditing records it, or the user the application named. For a BLOB saved
    /// over, the user of that save.
    /// </summary>
    public virtual Guid? CreatorId { get; set; }

    public virtual DateTime? LastModificationTime { get; set; }

    public virtual Guid? LastModifierId { get; set; }

    public virtual Guid? TenantId { get; protected set; }

    /// <summary>
    /// Whether an application saved the file under <see cref="Name"/> and reads it back by it. Such a file is not
    /// renamed or moved.
    /// </summary>
    public virtual bool IsAddressedByName => NameKey != null;

    /// <summary>
    /// Files the descriptor under <paramref name="directoryId"/> (<c>null</c>: the top of its container). Whether that
    /// directory may hold it is checked by <see cref="FileDescriptorManager"/>; never call this to bypass it.
    /// </summary>
    public virtual void SetDirectory(Guid? directoryId)
    {
        DirectoryId = directoryId;
    }

    /// <summary>
    /// Changes the display name of a file kept by id. <see cref="FileDescriptorManager.RenameAsync"/> refuses a file
    /// addressed by its name; never call this to bypass it.
    /// </summary>
    public virtual void Rename(string name)
    {
        Name = Check.NotNullOrWhiteSpace(name, nameof(name), FileDescriptorConsts.MaxNameLength);
    }

    /// <summary>
    /// Marks the file public or not. <see cref="FileDescriptorManager.SetPublicAsync"/> refuses a file addressed by its
    /// name, whose application decides it at each save; never call this to bypass it.
    /// </summary>
    public virtual void SetPublic(bool isPublic)
    {
        IsPublic = isPublic;
    }

    /// <summary>
    /// Marks the file pending: stored through an upload ticket, until its business system confirms it. Set before the
    /// descriptor is inserted.
    /// </summary>
    public virtual void MarkPending()
    {
        IsPending = true;
    }

    /// <summary>
    /// Confirms a pending file. <see cref="FileDescriptorManager.ConfirmAsync"/> saves it; a confirmed file is not
    /// pending again.
    /// </summary>
    public virtual void Confirm()
    {
        IsPending = false;
    }

    /// <summary>
    /// Replaces what the file holds, when its application saves under its name again: the new BLOB with its type, size
    /// and verified hash, the client that wrote it, the public mark - which each save sets anew - and when and for
    /// whom the bytes were stored. The id, the container, the name and its key stay: it is the same file at the same
    /// address. <see cref="FileDescriptorManager.SaveBlobAsync"/> calls it, and deletes the BLOB the file had; never
    /// call it otherwise.
    /// </summary>
    /// <param name="creationTime">When the new bytes were stored; <c>default</c> leaves it to ABP's auditing, as on an
    /// insert.</param>
    /// <param name="creatorId">The user the file is now counted for; <c>null</c> leaves it to ABP's auditing.</param>
    public virtual void ReplaceContent(
        string blobName,
        string mimeType,
        long size,
        string? hash,
        string? clientId,
        bool isPublic,
        DateTime creationTime,
        Guid? creatorId)
    {
        BlobName = Check.NotNullOrWhiteSpace(blobName, nameof(blobName), FileDescriptorConsts.MaxBlobNameLength);
        MimeType = Check.NotNullOrWhiteSpace(mimeType, nameof(mimeType), FileDescriptorConsts.MaxMimeTypeLength);
        Size = size;
        Hash = Check.Length(hash, nameof(hash), FileDescriptorConsts.MaxHashLength);
        ClientId = Check.Length(clientId, nameof(clientId), FileDescriptorConsts.MaxClientIdLength);
        IsPublic = isPublic;
        CreationTime = creationTime;
        CreatorId = creatorId;
    }

    /// <summary>
    /// SHA-256, as upper-case hex, of <c>{tenant}:{container}:{name}</c> - the tenant as 32 hexadecimal digits, or
    /// <c>host</c>.
    /// </summary>
    public static string CreateNameKey(Guid? tenantId, string containerName, string name)
    {
        var address = (tenantId?.ToString("N") ?? "host") + ":" + containerName + ":" + name;
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(address)));
    }
}
