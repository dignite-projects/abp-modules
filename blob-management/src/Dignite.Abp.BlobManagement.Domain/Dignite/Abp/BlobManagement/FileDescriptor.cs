using System;
using System.Security.Cryptography;
using System.Text;
using Volo.Abp;
using Volo.Abp.Auditing;
using Volo.Abp.Domain.Entities;
using Volo.Abp.MultiTenancy;

namespace Dignite.Abp.BlobManagement;

/// <summary>
/// One file in the BlobManagement: the record of bytes that <see cref="FileDescriptorManager"/> stored in a Blob Management container.
/// Every BLOB Blob Management holds has one, whichever entry point wrote it; tenant usage is computed from this table.
/// <para>
/// <b>Two names.</b> <see cref="Name"/> is the caller's: in a system container it is the BLOB name the application
/// saved under and reads back by, unique among the live descriptors of its tenant and container - held by the
/// <see cref="NameKey"/>, which the database keeps unique. <see cref="BlobName"/> is the physical BLOB in the container's storage, generated by the BlobManagement.
/// </para>
/// <para>
/// <b>Content dedup.</b> Bytes already stored in the same container (same tenant) are not stored again: the new
/// descriptor gets the <see cref="BlobName"/> of a live descriptor with the same <see cref="Hash"/>, and the BLOB is
/// removed only with the last live descriptor that names it. The descriptor that wrote a BLOB holds the
/// <see cref="DedupKey"/> while it is live - the arbiter that keeps two simultaneous uploads of the same bytes from
/// both storing them.
/// </para>
/// <para>
/// <b>In a user drive</b> the name is only a display name - the file is addressed by its id and names may repeat.
/// </para>
/// </summary>
public class FileDescriptor : AggregateRoot<Guid>, ICreationAuditedObject, IModificationAuditedObject, IDeletionAuditedObject, IMultiTenant
{
    protected FileDescriptor()
    {
    }

    /// <param name="ownsBlob">Whether this descriptor wrote <paramref name="blobName"/>, rather than sharing a BLOB
    /// another descriptor wrote; it then holds the <see cref="DedupKey"/>.</param>
    /// <param name="nameIsAddress">Whether <paramref name="name"/> is the file's address - a system container's file -
    /// so the descriptor holds the <see cref="NameKey"/>. The entity cannot tell the container's kind itself;
    /// <see cref="FileDescriptorManager"/> can.</param>
    public FileDescriptor(
        Guid id,
        string containerName,
        string name,
        string blobName,
        string mimeType,
        long size,
        string hash,
        bool ownsBlob,
        string? clientId = null,
        Guid? tenantId = null,
        bool nameIsAddress = false)
        : base(id)
    {
        ContainerName = Check.NotNullOrWhiteSpace(containerName, nameof(containerName), FileDescriptorConsts.MaxContainerNameLength);
        Name = Check.NotNullOrWhiteSpace(name, nameof(name), FileDescriptorConsts.MaxNameLength);
        BlobName = Check.NotNullOrWhiteSpace(blobName, nameof(blobName), FileDescriptorConsts.MaxBlobNameLength);
        MimeType = Check.NotNullOrWhiteSpace(mimeType, nameof(mimeType), FileDescriptorConsts.MaxMimeTypeLength);
        Size = size;
        Hash = Check.NotNullOrWhiteSpace(hash, nameof(hash), FileDescriptorConsts.MaxHashLength);
        ClientId = Check.Length(clientId, nameof(clientId), FileDescriptorConsts.MaxClientIdLength);
        TenantId = tenantId;
        DedupKey = ownsBlob ? CreateDedupKey(tenantId, containerName, hash) : null;
        NameKey = nameIsAddress ? CreateNameKey(tenantId, containerName, name) : null;
    }

    /// <summary>The Blob Management container the bytes are stored in (a container declared with <c>UseBlobManagementContainer</c>).</summary>
    public virtual string ContainerName { get; protected set; } = default!;

    /// <summary>
    /// The caller's name for the file. In a system container it is the address: the BLOB name the application saved
    /// under, kept as it was given (it may be a path).
    /// </summary>
    public virtual string Name { get; protected set; } = default!;

    /// <summary>
    /// The physical BLOB in the container's storage: 32 random hexadecimal digits and the canonical extension of
    /// the detected type, generated by <see cref="FileDescriptorManager"/>, shared by the descriptors that dedup to it.
    /// </summary>
    public virtual string BlobName { get; protected set; } = default!;

    /// <summary>Detected from the stored content, never the caller's claim.</summary>
    public virtual string MimeType { get; protected set; } = default!;

    /// <summary>
    /// SHA-256 of the uploaded bytes (upper-case hex), so the same upload dedups whether or not the container's
    /// contributors transformed it.
    /// </summary>
    public virtual string Hash { get; protected set; } = default!;

    /// <summary>The size of the stored bytes, after the container's pipeline contributors ran.</summary>
    public virtual long Size { get; protected set; }

    /// <summary>
    /// <c>{tenant}:{container}:{hash}</c> on the live descriptor that wrote <see cref="BlobName"/>, <c>null</c> on
    /// every other row. Unique in the database (rows with <c>null</c> do not collide), so of two simultaneous uploads
    /// of the same bytes only one can store them; it is cleared when the descriptor is deleted, so the same bytes can
    /// be stored again once no live descriptor has them.
    /// </summary>
    public virtual string? DedupKey { get; protected set; }

    /// <summary>
    /// On a live descriptor of a system container, the SHA-256 (upper-case hex) of <c>{tenant}:{container}:{name}</c>
    /// (<see cref="CreateNameKey"/>); <c>null</c> in a user drive, where names repeat, and on deleted rows. Unique in
    /// the database, so two simultaneous saves under one name cannot both leave a live descriptor - the lookup by name
    /// is check-then-act. A hash rather than the address itself, since unique-index keys are size-limited and a name
    /// may be long.
    /// </summary>
    public virtual string? NameKey { get; protected set; }

    /// <summary>The OAuth client that wrote the file through the BLOB API, or <c>null</c> (in-process, or a user).</summary>
    public virtual string? ClientId { get; protected set; }

    public virtual DateTime CreationTime { get; set; }

    public virtual Guid? CreatorId { get; set; }

    public virtual DateTime? LastModificationTime { get; set; }

    public virtual Guid? LastModifierId { get; set; }

    public virtual Guid? DeleterId { get; set; }

    public virtual DateTime? DeletionTime { get; set; }

    public virtual bool IsDeleted { get; set; }

    public virtual Guid? TenantId { get; protected set; }

    /// <summary>Whether this descriptor wrote its BLOB and still holds the <see cref="DedupKey"/>.</summary>
    public virtual bool OwnsBlob()
    {
        return DedupKey != null;
    }

    /// <summary>
    /// Gives up the <see cref="DedupKey"/>; done before the descriptor is deleted, so the deleted row does not keep
    /// the same bytes from being stored again. <see cref="ReleaseNameKey"/> does the same for the name.
    /// </summary>
    public virtual void ReleaseDedupKey()
    {
        DedupKey = null;
    }

    /// <summary>
    /// Gives up the <see cref="NameKey"/>: before the descriptor is deleted, and before an overriding save stores the
    /// descriptor that replaces it, since both cannot hold the key at once.
    /// </summary>
    public virtual void ReleaseNameKey()
    {
        NameKey = null;
    }

    /// <summary>
    /// Takes the <see cref="NameKey"/> (back): an overriding save whose new descriptor could not be stored returns the
    /// address to the descriptor it was going to replace. Only for a system container's file, whose name is its
    /// address.
    /// </summary>
    public virtual void ClaimNameKey()
    {
        NameKey = CreateNameKey(TenantId, ContainerName, Name);
    }

    public static string CreateDedupKey(Guid? tenantId, string containerName, string hash)
    {
        return (tenantId?.ToString("N") ?? "host") + ":" + containerName + ":" + hash;
    }

    /// <summary>
    /// SHA-256, as upper-case hex, of <c>{tenant}:{container}:{name}</c> - the tenant as 32 hexadecimal digits, or
    /// <c>host</c>.
    /// </summary>
    public static string CreateNameKey(Guid? tenantId, string containerName, string name)
    {
        var address = (tenantId?.ToString("N") ?? "host") + ":" + containerName + ":" + name;
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(address)));
    }
}
